create table if not exists public.daily_logs (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 log_date date not null,
 habits jsonb not null default '{}'::jsonb,
 notes text not null default '' check (char_length(notes) <= 1200),
 created_at timestamptz not null default now(),
 unique (user_id, log_date)
);
alter table public.daily_logs enable row level security;
drop policy if exists "Users read own logs" on public.daily_logs;
drop policy if exists "Users insert own logs" on public.daily_logs;
drop policy if exists "Users update own logs" on public.daily_logs;
drop policy if exists "Users delete own logs" on public.daily_logs;
create policy "Users read own logs" on public.daily_logs for select to authenticated using ((select auth.uid()) = user_id);
create policy "Users insert own logs" on public.daily_logs for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Users update own logs" on public.daily_logs for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Users delete own logs" on public.daily_logs for delete to authenticated using ((select auth.uid()) = user_id);
create index if not exists daily_logs_user_date_idx on public.daily_logs(user_id, log_date desc);
grant select,insert,update,delete on public.daily_logs to authenticated;
grant usage,select on sequence public.daily_logs_id_seq to authenticated;